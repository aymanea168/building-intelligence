/**
 * RAG API Service
 * 
 * Handles all communication with the backend RAG system.
 * Provides functions for uploading images and sending analysis requests.
 */

import api from "./client";

/**
 * Uploads an inspection image to the server
 * 
 * @param {File} file - The image file to upload (JPEG/PNG)
 * @returns {Promise<{path: string, filename: string}>} Upload result with file path
 * @throws {Error} If upload fails
 */
export async function uploadImage(file) {
  if (!file) {
    throw new Error("No file provided for upload");
  }

  const formData = new FormData();
  formData.append("file", file);

  try {
    const response = await api.post("/upload-only", formData, {
      headers: {
        "Content-Type": "multipart/form-data",
      },
    });
    return response.data;
  } catch (error) {
    throw new Error(`Image upload failed: ${error.message}`);
  }
}

/**
 * Sends a text/image prompt to the RAG analysis system
 * 
 * @param {string} prompt - Text description or query about the defect
 * @param {string} imgPath - Optional path to the inspection image (e.g., "media/crack.jpg")
 * @returns {Promise<{text: string}>} Analysis report generated by the RAG system
 * @throws {Error} If analysis fails
 */
export async function sendChat(prompt, imgPath = "") {
  if (!prompt) {
    throw new Error("Prompt cannot be empty");
  }

  try {
    const response = await api.post("/api/chat", {
      prompt: prompt,
      img_path: imgPath,
    });
    return response.data;
  } catch (error) {
    throw new Error(`Analysis failed: ${error.message}`);
  }
}